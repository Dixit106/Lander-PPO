import time
import pandas as pd
import os
from rich.live import Live
from rich.layout import Layout 
from rich.panel import Panel 
from rich.table import Table 
from rich.text import Text 
from rich import box 

LOG_FILE = "logs/monitor.monitor.csv"

def generate_layout() -> Layout:
    """Defines the grid for the terminal dashboard."""
    layout = Layout(name="root")
    layout.split_column(
        Layout(name="header", size=3),
        Layout(name="main", ratio=1)
    )
    layout["main"].split_row(
        Layout(name="stats", ratio=1),
        Layout(name="recent_episodes", ratio=2)
    )
    return layout 

def get_training_data():
    """Reads the CSV generated by Stable-baselines3 monitor"""
    if not os.path.exists(LOG_FILE):
        return None 

    try:
        # Fixed: skiprows=1
        df = pd.read_csv(LOG_FILE, skiprows=1)
        if len(df) == 0:
            return None
        return df
    except Exception:
        return None 

def create_stats_panel(df) -> Panel:
    if df is None:
        return Panel("Waiting for data...", title="Global Stats")

    total_episodes = len(df)
    best_score = df['r'].max()
    avg_last_100 = df['r'].tail(100).mean() if total_episodes >= 100 else df['r'].mean()

    # Color code the average score
    color = "red" if avg_last_100 < 0 else "yellow" if avg_last_100 < 150 else "green"

    last_mod_time = os.path.getmtime(LOG_FILE)
    time_since_last_update = time.time() - last_mod_time 

    if time_since_last_update > 15:
        status_text = "[bold red]TRAINING STOPPED[/]"
    else:
        status_text = "[blink green]TRAINING ACTIVE[/]"
    stats_text = (
        f"[b]Total Episodes:[/b] {total_episodes}\n\n"
        f"[b]Best Score:[/b] [cyan]{best_score:.2f}[/cyan]\n\n"
        f"[b]Avg Score (Last 100):[/b] [{color}]{avg_last_100:.2f}[/{color}]\n\n"
        f"[b]Status:[/b] {status_text}"
    )
    return Panel(Text.from_markup(stats_text), title="[b]Global Stats[/b]", border_style="cyan")

def create_episodes_table(df) -> Panel:
    """Builds a scrolling table of the 15 most recent landing attempts."""
    table = Table(box=box.SIMPLE, expand=True)
    table.add_column("Episode", style="dim")
    table.add_column("Score (Reward)", justify="right")
    table.add_column("Duration (Steps)", justify="right")

    if df is None:
        return Panel(table, title="Recent Flights")

    # Get last 15 rows and reverse them so the newest is at the top
    recent = df.tail(15).iloc[::-1]

    for i, row in recent.iterrows():
        score = row['r']
        # style the score text based on how good the landing was
        score_str = f"[green]{score:.2f}[/green]" if score > 100 else f"[red]{score:.2f}[/red]"
        table.add_row(str(i + 1), score_str, str(row['l']))

    return Panel(table, title="[b]Recent Flights[/b]", border_style="blue")

def main():
    layout = generate_layout()

    # The Live context manager updates the terminal automatically
    with Live(layout, refresh_per_second=2, screen=True):
        while True:
            # grabing the latest data
            df = get_training_data()

            # Build the UI component
            header = Panel("[b magenta]PROJECT LANDER-PPO :: NEURAL DESCENT TELEMETRY [/b magenta]", style="white on black")
            stats = create_stats_panel(df)
            episodes = create_episodes_table(df)

            # injecting components into the layout 
            layout["header"].update(header)
            layout["stats"].update(stats)
            layout["recent_episodes"].update(episodes)

            # sleep briefly before checking the file again
            time.sleep(1)

if __name__ == "__main__":
    main()